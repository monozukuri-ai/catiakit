#!/usr/bin/env python3
"""Check the license notice set and the dependency ledger (Python 3.11+).

`--write` regenerates `LICENSES/rust-dependencies.txt` from the locked registry
sources reported by `cargo metadata`. Without it the script only verifies.
"""
import argparse
import hashlib
import json
import re
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PROJECT_LICENSE = "PolyForm-Noncommercial-1.0.0"
LEDGER = "LICENSES/rust-dependencies.txt"
PINNED_TEXTS = {
    "LICENSES/PolyForm-Noncommercial-1.0.0.md": (
        "c0ea4a896d2c8c394b29f9427589996db826cd501c512279ff0ed3ef48fabbe5"
    ),
    "LICENSES/Apache-2.0.txt": (
        "c71d239df91726fc519c6eb72d318ec65820627232b2f796219e87dcf35d0ab4"
    ),
    "LICENSES/CC-BY-4.0.txt": (
        "d557539df68e771cc1eedcc91d13f70fca930e508d11eedcafa4b15db49e3744"
    ),
}
NOTICE_PATHS = ("LICENSE", "COMMERCIAL-LICENSE.md", "THIRD_PARTY_NOTICES.md", "docs/license.md")
REQUIRED_NOTICES = (
    "Required Notice: catiakit is licensed by UnRobotics Inc. "
    "(https://www.un-robotics.com/).",
    "Required Notice: catiakit is offered under PolyForm Noncommercial 1.0.0; "
    "separate commercial licenses are available.",
)
# Dependency license expressions reviewed for this project. Anything else
# stops the ledger generation until it is reviewed and added here.
REVIEWED_LICENSES = {
    "MIT",
    "MIT OR Apache-2.0",
    "Apache-2.0 OR MIT",
    "Unlicense OR MIT",
    "(MIT OR Apache-2.0) AND Unicode-3.0",
}
HEADER = re.compile(r"^===== (\S+) (\S+): (\S+) =====$", re.MULTILINE)


def require(condition, message):
    if not condition:
        raise ValueError(message)


def locked_packages(root=ROOT):
    lock = tomllib.loads((root / "Cargo.lock").read_text("utf-8"))
    return {(p["name"], p["version"]) for p in lock["package"] if "source" in p}


def registry_packages(root=ROOT):
    output = subprocess.check_output(
        ["cargo", "metadata", "--locked", "--offline", "--format-version", "1"],
        cwd=root,
    )
    packages = [p for p in json.loads(output)["packages"] if p["source"] is not None]
    return sorted(packages, key=lambda p: (p["name"], p["version"]))


def selected_license_files(package):
    base = Path(package["manifest_path"]).parent
    candidates = sorted(
        f
        for f in base.iterdir()
        if f.is_file()
        and f.name.upper().startswith(("LICENSE", "COPYING", "COPYRIGHT", "NOTICE"))
    )
    require(candidates, f"no license text in registry source for {package['name']}")
    expression = package["license"] or ""
    require(expression in REVIEWED_LICENSES, f"unreviewed dependency license: {package['name']}: {expression}")
    mit = [f for f in candidates if "MIT" in f.name.upper()]
    if mit and "MIT" in expression:
        # MIT is selected where offered; mandatory additional terms stay.
        keep = {f for f in candidates if f in mit or "UNICODE" in f.name.upper() or "NOTICE" in f.name.upper()}
        return sorted(keep)
    return candidates


def write_ledger(root=ROOT):
    sections = []
    for package in registry_packages(root):
        base = Path(package["manifest_path"]).parent
        for path in selected_license_files(package):
            text = path.read_text("utf-8", errors="replace").rstrip()
            sections.append(
                f"===== {package['name']} {package['version']}: {path.relative_to(base).as_posix()} =====\n\n{text}\n"
            )
    body = (
        "Notices for the Cargo.lock dependency graph, including build and development dependencies.\n"
        "Generated by tools/license/check_license.py --write from the locked registry sources.\n"
        "MIT is selected where a crate offers it as an alternative; mandatory additional terms follow their crate.\n"
        "The listed crate sources are not vendored in this repository.\n\n" + "\n".join(sections)
    )
    (root / LEDGER).write_text(body, "utf-8")


def check(root=ROOT):
    workspace = tomllib.loads((root / "Cargo.toml").read_text("utf-8"))["workspace"]
    require(workspace["package"].get("license") == PROJECT_LICENSE, "workspace license mismatch")
    for member in workspace["members"]:
        manifest = tomllib.loads((root / member / "Cargo.toml").read_text("utf-8"))["package"]
        require(manifest.get("license") == {"workspace": True}, f"{member}: crate license must inherit the workspace value")
    fuzz = tomllib.loads((root / "fuzz/Cargo.toml").read_text("utf-8"))["package"]
    require(fuzz.get("license") == PROJECT_LICENSE, "fuzz crate license mismatch")
    for name in NOTICE_PATHS:
        require((root / name).is_file(), f"missing notice file: {name}")
    for name, digest in PINNED_TEXTS.items():
        actual = hashlib.sha256((root / name).read_bytes()).hexdigest()
        require(actual == digest, f"changed canonical license text: {name}")
    lines = (root / "LICENSE").read_text("utf-8").splitlines()
    require(all(n in lines for n in REQUIRED_NOTICES), "LICENSE is missing a Required Notice line")
    ledger = (root / LEDGER).read_text("utf-8")
    covered = {(m.group(1), m.group(2)) for m in HEADER.finditer(ledger)}
    missing = locked_packages(root) - covered
    require(not missing, f"dependency notices missing from {LEDGER}: {sorted(missing)}")
    stale = covered - locked_packages(root)
    require(not stale, f"stale dependency notices in {LEDGER}: {sorted(stale)}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="regenerate the dependency ledger from Cargo.lock")
    args = parser.parse_args()
    if args.write:
        write_ledger()
    check()
    print("License notices, canonical texts and dependency ledger passed")


if __name__ == "__main__":
    try:
        main()
    except ValueError as error:
        print(f"license check failed: {error}", file=sys.stderr)
        sys.exit(1)
